package workflow

import (
	"context"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func noteFor(t *testing.T, notes []FileNote, p string) FileNote {
	t.Helper()
	for _, n := range notes {
		if n.Path == p {
			return n
		}
	}
	t.Fatalf("%s not in %+v", p, notes)
	return FileNote{}
}

func TestStagedFilesAndKinds(t *testing.T) {
	e := newEnv(t)
	dir := e.repo()
	write(t, filepath.Join(dir, "old.go"), "package a\n\nfunc A() {}\nfunc B() {}\nfunc C() {}\n")
	write(t, filepath.Join(dir, "gone.txt"), "1\n2\n")
	write(t, filepath.Join(dir, "run.sh"), "echo\n")
	e.commit(dir, "Initial")

	e.git(dir, "mv", "old.go", "new name.go")
	write(t, filepath.Join(dir, "new name.go"), "package a\n\nfunc A() {}\nfunc B() {}\nfunc C() {}\nfunc D() {}\n")
	os.Remove(filepath.Join(dir, "gone.txt"))
	os.Chmod(filepath.Join(dir, "run.sh"), 0o755)
	write(t, filepath.Join(dir, "src/main.go"), "package main\n\nfunc main() {}\n")
	write(t, filepath.Join(dir, "web/package-lock.json"), "{\n\"a\": 1\n}\n")
	write(t, filepath.Join(dir, "api/api.pb.go"), "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage api\n")
	write(t, filepath.Join(dir, "gen/schema.ts"), "export type A = 1\n")
	write(t, filepath.Join(dir, ".gitattributes"), "gen/** linguist-generated\n")
	write(t, filepath.Join(dir, "app.min.js"), "var a=1\n")
	write(t, filepath.Join(dir, "img.png"), "\x89PNG\x00\x01\x02")
	write(t, filepath.Join(dir, "empty.txt"), "")
	write(t, filepath.Join(dir, "doc.md"), "Mentions // Code generated in prose.\n")
	e.git(dir, "add", "-A")
	r, _ := e.open(dir)
	ctx := context.Background()

	notes, err := r.stagedFiles(ctx)
	if err != nil {
		t.Fatal(err)
	}
	if err := r.classify(ctx, notes); err != nil {
		t.Fatal(err)
	}
	if n := noteFor(t, notes, "new name.go"); n.Status != "R" || n.OrigPath != "old.go" || n.Added != 1 || n.Treatment != TreatFull {
		t.Fatalf("rename %+v", n)
	}
	for p, reason := range map[string]string{
		"gone.txt":              ReasonDeleted,
		"run.sh":                ReasonNoText,
		"web/package-lock.json": ReasonLock,
		"api/api.pb.go":         ReasonGenerated,
		"gen/schema.ts":         ReasonGenerated,
		"app.min.js":            ReasonGenerated,
		"img.png":               ReasonBinary,
		"empty.txt":             ReasonNoText,
	} {
		n := noteFor(t, notes, p)
		if n.Treatment != TreatSummary || len(n.Reasons) != 1 || n.Reasons[0] != reason {
			t.Errorf("%s: %+v", p, n)
		}
	}
	for _, p := range []string{"src/main.go", "doc.md", ".gitattributes"} {
		if n := noteFor(t, notes, p); n.Treatment != TreatFull {
			t.Errorf("%s treated as %+v", p, n)
		}
	}
	if n := noteFor(t, notes, "gone.txt"); n.Deleted != 2 {
		t.Fatalf("deleted %+v", n)
	}
	if l := noteFor(t, notes, "run.sh").line(); !strings.Contains(l, "mode 100644→100755") {
		t.Fatalf("mode line %q", l)
	}
	if l := noteFor(t, notes, "img.png").line(); strings.Contains(l, "+0") || !strings.Contains(l, "binary") {
		t.Fatalf("binary line %q", l)
	}
	if l := noteFor(t, notes, "new name.go").line(); l != "R new name.go (from old.go) +1 -0" {
		t.Fatalf("rename line %q", l)
	}
}

func TestGeneratedAttributeComesFromTheIndex(t *testing.T) {
	e := newEnv(t)
	dir := e.repo()
	write(t, filepath.Join(dir, "gen/a.ts"), "export const a = 1\n")
	e.git(dir, "add", "-A")
	// Only in the working tree, not staged: it does not count.
	write(t, filepath.Join(dir, ".gitattributes"), "gen/** linguist-generated\n")
	r, _ := e.open(dir)
	notes, _ := r.stagedFiles(context.Background())
	if err := r.classify(context.Background(), notes); err != nil {
		t.Fatal(err)
	}
	if n := noteFor(t, notes, "gen/a.ts"); n.Treatment != TreatFull {
		t.Fatalf("unstaged attributes used: %+v", n)
	}
}
