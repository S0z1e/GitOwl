// bigSource is a Go file of n functions, about 60 bytes each.
func bigSource(name string, n int, version string) string {
	var b strings.Builder
	b.WriteString("package big\n\n")
	for i := range n {
		b.WriteString("func " + name + itoa(i) + "() string { return \"" + version + " " + itoa(i) + "\" }\n\n")
	}
	return b.String()
}

func TestLargeStagedChangeIsCompactedAndSentOnce(t *testing.T) {
	for _, initial := range []bool{false, true} {
		t.Run(map[bool]string{false: "with history", true: "initial commit"}[initial], func(t *testing.T) {
			e, f, _, cfg := aiEnv(t)
			dir := e.repo()
			if !initial {
				write(t, filepath.Join(dir, "alpha.go"), bigSource("Alpha", 1500, "v1"))
				write(t, filepath.Join(dir, "beta.go"), bigSource("Beta", 1500, "v1"))
				write(t, filepath.Join(dir, "old_name.go"), bigSource("Moved", 30, "v1"))
				e.commit(dir, "Add the big package")
			}
			// Many changed hunks in two large files: over 120 KB of diff.
			write(t, filepath.Join(dir, "alpha.go"), bigSource("Alpha", 1500, "v2"))
			write(t, filepath.Join(dir, "beta.go"), bigSource("Beta", 1500, "v2"))
			if !initial {
				e.git(dir, "mv", "old_name.go", "new_name.go")
			} else {
				write(t, filepath.Join(dir, "new_name.go"), bigSource("Moved", 30, "v1"))
			}
			write(t, filepath.Join(dir, "small.go"), "package big\n\nfunc Small() int { return 42 }\n")
			write(t, filepath.Join(dir, "web/package-lock.json"), strings.Repeat("{\"name\": \"dep\", \"version\": \"1.0.0\"},\n", 3000))
			write(t, filepath.Join(dir, "api/types.pb.go"), "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage api\n"+strings.Repeat("var GENERATED = 1\n", 2000))
			write(t, filepath.Join(dir, "logo.png"), "\x89PNG\r\n\x1a\n\x00\x00binary")
			write(t, filepath.Join(dir, "min.js"), "var x="+strings.Repeat("1+", 5000)+"1;\n") // one very long line
			e.git(dir, "add", "-A")
			// Unstaged and untracked content never goes in.
			write(t, filepath.Join(dir, "small.go"), "package big\n\nfunc Small() int { return UNSTAGED }\n")
			write(t, filepath.Join(dir, "notes.txt"), "UNTRACKED\n")
			if out := e.git(dir, "diff", "--cached"); len(out) < 120_000 {
				t.Fatalf("diff only %d bytes", len(out))
			}
			r, snap := e.open(dir)

			req, d, err := r.Draft(context.Background(), DraftOptions{}, cfg)
			if err != nil || d.Text == "" {
				t.Fatal(err)
			}
			if f.count() != 2 {
				t.Fatalf("%d calls", f.count())
			}
			sent := f.last().Messages
			if req.Estimate > req.Budget.Input || requestEstimate(req, "") != req.Estimate {
				t.Fatalf("estimate %d (sent %d) over %d", req.Estimate, EstimateTokens(sent), req.Budget.Input)
			}
			user := sent[1].Content
			if strings.Contains(user, "UNSTAGED") || strings.Contains(user, "UNTRACKED") || strings.Contains(user, "notes.txt") {
				t.Fatal("unstaged or untracked content sent")
			}
			if !strings.Contains(sent[0].Content, "not shown in full") || !strings.Contains(user, "shortened as the file list says") {
				t.Fatal("the model is not told the input is incomplete")
			}
			// Every staged file is in the list, once.
			if len(req.Notes) != len(snap.Staged) {
				t.Fatalf("%d notes for %d staged files", len(req.Notes), len(snap.Staged))
			}
			for _, ch := range snap.Staged {
				if !strings.Contains(user, " "+ch.Path) {
					t.Fatalf("%s not listed:\n%s", ch.Path, user[:min(len(user), 2000)])
				}
			}
			reasons := map[string]string{
				"web/package-lock.json": ReasonLock,
				"api/types.pb.go":       ReasonGenerated,
				"logo.png":              ReasonBinary,
			}
			for _, n := range req.Notes {
				if want, ok := reasons[n.Path]; ok && (n.Treatment != TreatSummary || n.Reasons[0] != want) {
					t.Errorf("%s: %+v", n.Path, n)
				}
				if n.Path == "min.js" && !strings.Contains(n.line(), "long lines cut") {
					t.Errorf("long line not noted: %q", n.line())
				}
				if n.Path == "new_name.go" && !initial && n.OrigPath != "old_name.go" {
					t.Errorf("rename source lost: %+v", n)
				}
			}
			if strings.Contains(user, "GENERATED = 1") || strings.Contains(user, "\"version\": \"1.0.0\"") {
				t.Fatal("lock or generated content sent")
			}
			// Both large files get part of their changes, not only the first,
			// and the small file is whole.
			for _, want := range []string{"Alpha", "Beta", "+func Small() int { return 42 }"} {
				if !strings.Contains(req.Diff, want) {
					t.Fatalf("%q missing from the diff", want)
				}
			}
			if strings.Contains(user, strings.Repeat("1+", 200)) {
				t.Fatal("long line not cut")
			}
		})
	}
}

func TestCompactionReadsOnlyPartOfAHugeFile(t *testing.T) {
	e, f, _, cfg := aiEnv(t)
	dir := e.repo()
	// 8 MB staged: GitOwl reads at most its read limit of it.
	write(t, filepath.Join(dir, "huge.txt"), strings.Repeat("a line of a very large text file\n", 250_000))
	e.git(dir, "add", "huge.txt")
	r, _ := e.open(dir)
	req, _, err := r.Draft(context.Background(), DraftOptions{}, cfg)
	if err != nil || f.count() != 2 {
		t.Fatalf("%v %d", err, f.count())
	}
	n := req.Notes[0]
	if !strings.Contains(n.line(), "only the start of the diff was read") || n.Added != 250_000 {
		t.Fatalf("%q", n.line())
	}
	if info, _ := os.Stat(filepath.Join(dir, "huge.txt")); info.Size() < 8_000_000 {
		t.Fatal("file not as large as intended")
	}
}
